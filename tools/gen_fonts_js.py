#!/usr/bin/env python3
"""Generate data/js/fonts.js (glyph data for the web UI preview) from src/digits.h.

Re-run after editing the fonts:  python3 tools/gen_fonts_js.py
Verify it is up to date (CI):     python3 tools/gen_fonts_js.py --check
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from render import load_fonts  # noqa: E402

USED = ["Time", "Temp", "UserBold"]  # fonts the preview draws

fonts = load_fonts(os.path.join(ROOT, "src", "digits.h"))
out = {
    name: {"glyphs": [{"w": g["width"], "rows": g["rows"]} for g in fonts[name]["glyphs"]]}
    for name in USED
}
path = os.path.join(ROOT, "data", "js", "fonts.js")
content = (
    "// Generated by tools/gen_fonts_js.py from src/digits.h. Do not edit.\n"
    "const CLOCK_FONTS = " + json.dumps(out, separators=(",", ":")) + ";\n"
)

if "--check" in sys.argv:
    current = open(path).read() if os.path.exists(path) else ""
    if current != content:
        sys.exit("data/js/fonts.js is stale: run python3 tools/gen_fonts_js.py")
    print("fonts.js is up to date")
else:
    with open(path, "w") as f:
        f.write(content)
    print(f"wrote {path}")
